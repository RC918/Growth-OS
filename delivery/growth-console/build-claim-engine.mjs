// Deterministic browser packaging of the unchanged offline verifier. No runtime
// dependency, model invocation or alternate verifier semantics.
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
export async function claimEngineSource() {
  const root = new URL('../../', import.meta.url);
  const pipeline = await readFile(new URL('prototype/ai-seo/ai-seo-pipeline.mjs', root), 'utf8');
  const verifier = await readFile(new URL('prototype/ai-seo/claim-verifier.mjs', root), 'utf8');
  const hook = "import {FUNCTION_WORDS, trustedFacts, verifySuggestions} from './ai-seo-pipeline.mjs';";
  if (verifier.split(hook).length !== 2 || /^import /m.test(pipeline)) throw Error('CLAIM_ENGINE_IMPORT_CHANGED');
  const local = source => source.replace(/^export (?=(?:async )?(?:function|const) )/gm, '').replace(/^export \{[^}]+\};\s*$/gm, '');
  return '// Generated by delivery/growth-console/build-claim-engine.mjs; edit upstream sources only.\n'
    + 'const pipeline = (() => {\n' + local(pipeline) + '\nreturn {FUNCTION_WORDS, trustedFacts, verifySuggestions};\n})();\n'
    + 'const engine = (() => {\n' + local(verifier.replace(hook, 'const {FUNCTION_WORDS, trustedFacts, verifySuggestions} = pipeline;'))
    + '\nreturn {verifyClaims};\n})();\nexport const verifyClaims = engine.verifyClaims;\n';
}
export async function buildClaimEngine() {
  await writeFile(new URL('../../apps/web/console-claim-engine.mjs', import.meta.url), await claimEngineSource());
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await buildClaimEngine();
